import type { Block, DocumentModel } from './templates.js';

function escapeHtml(value: string): string {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

const TONES: Record<string, string> = {
  draft: 'background:#fff4e5;border-left:4px solid #f59e0b;color:#7c4a03;',
  info: 'background:#eef4ff;border-left:4px solid #2563eb;color:#1e3a8a;',
  warn: 'background:#fef2f2;border-left:4px solid #dc2626;color:#7f1d1d;',
};

export function blockToHtml(block: Block): string {
  switch (block.kind) {
    case 'heading':
      return `<h2>${escapeHtml(block.text)}</h2>`;
    case 'paragraph':
      return `<p>${escapeHtml(block.text)}</p>`;
    case 'bullets':
      return `<ul>${block.items.map((i) => `<li>${escapeHtml(i)}</li>`).join('')}</ul>`;
    case 'kv':
      return `<table class="kv">${block.rows
        .map(([k, v]) => `<tr><th>${escapeHtml(k)}</th><td>${escapeHtml(v)}</td></tr>`)
        .join('')}</table>`;
    case 'table':
      return `<table class="grid"><thead><tr>${block.headers
        .map((h) => `<th>${escapeHtml(h)}</th>`)
        .join('')}</tr></thead><tbody>${block.rows
        .map((row) => `<tr>${row.map((cell) => `<td>${escapeHtml(cell)}</td>`).join('')}</tr>`)
        .join('')}</tbody></table>`;
    case 'notice':
      return `<div class="notice" style="${TONES[block.tone] ?? TONES.info}">${escapeHtml(block.text)}</div>`;
    default:
      return '';
  }
}

